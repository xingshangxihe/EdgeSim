/*
 * =============================================================================
 * EdgeSim UI 模块独立测试  test_ui_lvgl.c
 * =============================================================================
 * 【测试目标】
 *   验证 ui_lvgl 模块可独立启动、显示界面、响应事件。
 *   不依赖真实业务层（multi_proc 子进程未启动）。
 *
 * 【测试流程】
 *   1. ui_init 初始化 SDL2 + LVGL + 4 个窗口 + pipeline timer
 *   2. 进入 ui_loop 主循环
 *   3. 用户点窗口关闭按钮或 ESC 退出
 *
 * 【注意事项】
 *   由于 multi_proc 未启动，proc_recv/proc_send 会返回 -1，
 *   ui_pipeline timer 会打印错误日志但不影响界面显示。
 *   真实集成测试需在父进程中先调用 proc_init。
 * =============================================================================
 */

#include "ui_lvgl.h"
#include <stdio.h>

int main(int argc, char **argv)
{
    int ret;

    printf("============================================================\n");
    printf("  EdgeSim ui_lvgl 模块独立测试\n");
    printf("============================================================\n\n");

    printf("【步骤 1】ui_init\n");
    ret = ui_init(argc, argv);
    if (ret != 0) {
        printf("  UI 初始化失败\n");
        return 1;
    }
    printf("  UI 初始化成功\n\n");

    printf("【步骤 2】ui_loop 主循环\n");
    printf("  - 鼠标点击窗口或控件进行交互\n");
    printf("  - 按 ESC 或点窗口关闭按钮退出\n\n");

    /* 主循环：ui_loop 返回 0=继续，-1=退出 */
    while (ui_loop() == 0) {
        /* 空循环，所有工作由 ui_loop 内部完成 */
    }

    printf("\n【步骤 3】ui_deinit\n");
    ui_deinit();
    printf("  UI 资源已释放\n");

    printf("\n============================================================\n");
    printf("  测试完成\n");
    printf("============================================================\n");
    return 0;
}
