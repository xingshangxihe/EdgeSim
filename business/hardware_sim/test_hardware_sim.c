/*
 * =============================================================================
 * EdgeSim 内存仿真模块独立测试  test_hardware_sim.c
 * =============================================================================
 * 【文件作用】
 *   独立测试 hardware_sim 模块的四大核心接口：
 *     1. mem_sim_get_usage()    —— 内存读取
 *     2. mem_sim_alloc()        —— 256MB 阈值限制
 *     3. mem_sim_unload_idle()  —— 闲置模型释放
 *     4. mem_sim_gen_report()   —— 性能报表
 *   包含一个 main() 函数，可单独编译运行，无需依赖其它模块。
 *
 * 【编译运行方式】
 *   在 business/hardware_sim/ 目录下执行：
 *     make test          # 一键编译并运行
 *   或手动编译：
 *     gcc -Wall -g test_hardware_sim.c hardware_sim.c -o test_hardware_sim -lpthread
 *     ./test_hardware_sim
 *
 * 【设计文档对应】
 *   EdgeSim_Design.md 第 3.1 节 + 第 7.2 条「底层核心代码必须逐行阅读、编译自测」
 * =============================================================================
 */

#include <stdio.h>          /* printf */
#include <string.h>         /* strncpy */
#include "hardware_sim.h"   /* 本模块接口 */


/* =============================================================================
 * 辅助函数：打印当前内存使用快照
 * =============================================================================
 * 封装 mem_sim_get_usage 调用并格式化输出，避免测试代码重复。
 * ========================================================================== */
static void print_usage(const char *tag)
{
    mem_usage_t usage;                                   /* 内存快照变量 */

    /* 调用接口获取快照 */
    if (mem_sim_get_usage(&usage) != 0) {
        printf("[%s] 获取内存使用失败\n", tag);
        return;
    }

    /* 打印快照。
     * 【阶段 6 修复】mem_usage_t 的字段在浮点化改造后是 double，
     * 旧代码用 %zu（size_t）打印会按 size_t 位模式读取 double，
     * 输出垃圾值（如"上限=1MB、剩余=巨大数"）。
     * 全部改用 %.1f（double，保留 1 位小数）。 */
    printf("[%s] 上限=%.1fMB 已用=%.1fMB 剩余=%.1fMB 使用率=%.2f%%\n",
           tag,
           usage.total_limit_mb,
           usage.used_mb,
           usage.free_mb,
           usage.usage_percent);
}


/* =============================================================================
 * 辅助函数：给模型设置名称与量化体积（模拟真实加载）
 * =============================================================================
 * 由于 hardware_sim.c 的 g_model_table 是 static，外部无法直接访问，
 * 这里通过"先 alloc 再通过 record_inference 间接体现"的方式模拟。
 * 模型名称在首次 alloc 时由模块内部设默认值，本测试通过 record 体现活跃度。
 * ========================================================================== */
static void simulate_inference(int model_id, double latency_ms, int times)
{
    int i;
    for (i = 0; i < times; i++) {
        mem_sim_record_inference(model_id, latency_ms);
    }
    printf("[simulate] 模型 ID=%d 模拟推理 %d 次，每次 %.2f ms\n",
           model_id, times, latency_ms);
}


/* =============================================================================
 * 主测试函数
 * =============================================================================
 * 测试流程设计：
 *   步骤 1：初始化为 256MB 上限（对标设计文档「256MB 上限可稳定运行」）
 *   步骤 2：测试【内存读取】接口
 *   步骤 3：加载 LLM + OCR 模型，制造不同访问频次
 *   步骤 4：测试【256MB 阈值限制】—— 申请触发 90% 阈值，观察自动回收
 *   步骤 5：测试【闲置模型释放】—— 主动调用 mem_sim_unload_idle()
 *   步骤 6：测试超限拒绝场景
 *   步骤 7：测试【性能报表】接口
 *   步骤 8：清理释放
 * ========================================================================== */
int main(void)
{
    int ret;                                            /* 接口返回值缓存 */
    int unloaded_id;                                    /* 被卸载的模型 ID */

    printf("============================================================\n");
    printf("  EdgeSim hardware_sim 模块独立测试开始\n");
    printf("============================================================\n\n");

    /* ----------------------------------------------------------------------
     * 步骤 1：初始化内存仿真器，上限 256MB
     * ---------------------------------------------------------------------- */
    printf("【步骤 1】初始化内存仿真器（上限 256MB）\n");
    ret = mem_sim_init(256);
    if (ret != 0) {
        printf("  ✗ 初始化失败\n");
        return 1;
    }
    printf("  ✓ 初始化成功\n\n");

    /* ----------------------------------------------------------------------
     * 步骤 2：测试【内存读取】接口
     * ---------------------------------------------------------------------- */
    printf("【步骤 2】测试内存读取接口 mem_sim_get_usage()\n");
    print_usage("初始状态");
    printf("  ✓ 内存读取接口正常\n\n");

    /* ----------------------------------------------------------------------
     * 步骤 3：加载 LLM 模型（150MB）和 OCR 模型（80MB）
     * ---------------------------------------------------------------------- */
    printf("【步骤 3】加载模型，制造不同访问频次\n");

    /* 加载 LLM，占 150MB（58.6%） */
    ret = mem_sim_alloc(150, MODEL_ID_LLM);
    if (ret != 0) {
        printf("  ✗ LLM 加载失败\n");
        return 1;
    }

    /* 加载 OCR，占 80MB（当前已用 230MB，89.8%，刚好低于 90% 阈值） */
    ret = mem_sim_alloc(80, MODEL_ID_OCR);
    if (ret != 0) {
        printf("  ✗ OCR 加载失败\n");
        return 1;
    }

    /* 模拟推理：LLM 访问 10 次（高活跃），OCR 访问 1 次（低活跃=闲置） */
    simulate_inference(MODEL_ID_LLM, 1850.5, 10);
    simulate_inference(MODEL_ID_OCR, 820.3, 1);

    print_usage("加载LLM+OCR后");
    printf("  ✓ 模型加载完成\n\n");

    /* ----------------------------------------------------------------------
     * 步骤 4：测试【256MB 阈值限制】—— 申请 ASR 50MB，将触发自动回收
     * ---------------------------------------------------------------------- */
    printf("【步骤 4】测试 256MB 阈值限制（申请 ASR 50MB）\n");
    printf("  预期：230+50=280MB 将超过 90%% 阈值(230.4MB)，自动卸载最闲置模型\n");
    printf("  预期：OCR(access=1) 比 LLM(access=10) 更闲置，应被优先卸载\n\n");

    /* 230 + 50 = 280MB，超过 90% 阈值(230.4MB)，触发自动回收。
     * 回收 OCR(80MB) 后：230-80=150MB，150+50=200MB < 230.4MB，回收停止。
     * ASR 50MB 分配成功，最终已用 200MB。 */
    ret = mem_sim_alloc(50, MODEL_ID_ASR);
    if (ret == 0) {
        printf("  ✓ ASR 申请成功\n");
    } else {
        printf("  ✗ ASR 申请失败（不符合预期）\n");
    }
    print_usage("阈值限制触发后");
    printf("\n");

    /* ----------------------------------------------------------------------
     * 步骤 5：测试【闲置模型释放】—— 主动调用 mem_sim_unload_idle()
     * ---------------------------------------------------------------------- */
    printf("【步骤 5】测试闲置模型释放接口 mem_sim_unload_idle()\n");
    printf("  当前已加载：LLM(access=10) + ASR(access=1)\n");
    printf("  预期：ASR(access=1) 最闲置，应被卸载\n\n");

    /* 再给 LLM 多几次访问，确保 LLM 比 ASR 活跃 */
    simulate_inference(MODEL_ID_LLM, 1900.0, 5);

    unloaded_id = mem_sim_unload_idle();
    if (unloaded_id >= 0) {
        printf("  ✓ 卸载了模型 ID=%d\n", unloaded_id);
        /* 校验是否真的卸载了 ASR（最闲置的） */
        if (unloaded_id == MODEL_ID_ASR) {
            printf("  ✓ 符合预期：ASR 被卸载\n");
        } else {
            printf("  ⚠ 注意：卸载的不是 ASR，请检查闲置判定逻辑\n");
        }
    } else {
        printf("  ✗ 无模型被卸载\n");
    }
    print_usage("闲置释放后");
    printf("\n");

    /* ----------------------------------------------------------------------
     * 步骤 6：测试超限拒绝场景
     * ---------------------------------------------------------------------- */
    printf("【步骤 6】测试超限拒绝（申请 300MB 超过硬上限）\n");
    printf("  当前已用约 150MB(LLM)，申请 300MB 必超过 256MB 硬上限\n");
    printf("  预期：自动回收 LLM(150MB) 后 0+300=300>256MB，仍超限，拒绝\n\n");

    /* 当前 LLM 150MB，申请 300MB：
     *   - 预测 150+300=450MB >= 90%% 阈值(230.4MB)，触发自动回收
     *   - 回收 LLM(150MB) 后 used=0，预测 0+300=300MB 仍 >= 阈值，继续
     *   - 无更多模型可回收，退出循环
     *   - 300MB > 256MB 硬上限，拒绝申请
     * 这样验证了"即使回收所有模型仍超限则拒绝"的硬上限保护逻辑。 */
    ret = mem_sim_alloc(300, MODEL_ID_OCR);
    if (ret != 0) {
        printf("  ✓ 申请 300MB 被正确拒绝（超过 256MB 硬上限）\n");
    } else {
        printf("  ⚠ 申请 300MB 成功（不符合预期，请检查硬上限判定）\n");
    }
    print_usage("超限拒绝后");
    printf("\n");

    /* ----------------------------------------------------------------------
     * 步骤 7：测试【性能报表】接口
     * ---------------------------------------------------------------------- */
    printf("【步骤 7】测试性能报表接口 mem_sim_gen_report()\n");

    /* 重新加载模型，制造完整数据 */
    mem_sim_alloc(150, MODEL_ID_LLM);
    mem_sim_record_inference(MODEL_ID_LLM, 1820.5);
    mem_sim_alloc(60, MODEL_ID_OCR);
    mem_sim_record_inference(MODEL_ID_OCR, 780.4);

    ret = mem_sim_gen_report("perf_report.txt");
    if (ret == 0) {
        printf("  ✓ 报表已生成：perf_report.txt\n");
        printf("  提示：用 cat perf_report.txt 查看完整内容\n");
    } else {
        printf("  ✗ 报表生成失败\n");
    }
    printf("\n");

    /* ----------------------------------------------------------------------
     * 步骤 8：清理释放
     * ---------------------------------------------------------------------- */
    printf("【步骤 8】清理所有模型\n");
    mem_sim_free(MODEL_ID_LLM);
    mem_sim_free(MODEL_ID_OCR);
    mem_sim_free(MODEL_ID_ASR);
    print_usage("清理后");

    printf("\n============================================================\n");
    printf("  测试全部完成\n");
    printf("============================================================\n");

    return 0;
}
